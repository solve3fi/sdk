// Converts the program's current Anchor IDL (spec 0.1.0, snake_case) into the legacy Anchor 0.29 IDL format
// (camelCase) that this SDK's `Program` wrapper expects, and writes packages/sdk/src/artifacts/solve.{json,ts}.
//   node scripts/convert-idl.mjs [idl/solve.json]
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const input = process.argv[2] ?? fileURLToPath(new URL("../idl/solve.json", import.meta.url));
const idl = JSON.parse(readFileSync(input, "utf8"));
const camel = (s) => s.replace(/_([a-z0-9])/g, (_, c) => c.toUpperCase());
const typeOf = (t) => {
	if (typeof t === "string") return t === "pubkey" ? "publicKey" : t;
	if (t.defined) return { defined: typeof t.defined === "string" ? t.defined : t.defined.name };
	if (t.option) return { option: typeOf(t.option) };
	if (t.vec) return { vec: typeOf(t.vec) };
	if (t.array) return { array: [typeOf(t.array[0]), t.array[1]] };
	throw new Error(`Unsupported IDL type ${JSON.stringify(t)}`);
};
const field = (f) => ({ name: camel(f.name), type: typeOf(f.type) });
const typeDef = (t) => {
	const ty = t.type;
	if (ty.kind === "struct") return { name: t.name, type: { kind: "struct", fields: (ty.fields ?? []).map(field) } };
	if (ty.kind === "enum")
		return {
			name: t.name,
			type: {
				kind: "enum",
				variants: ty.variants.map((v) => ({
					name: v.name,
					...(v.fields ? { fields: v.fields.map((f) => (typeof f === "object" && f.name ? field(f) : typeOf(f))) } : {}),
				})),
			},
		};
	throw new Error(`Unsupported type kind ${ty.kind}`);
};
const accountNames = new Set(idl.accounts.map((a) => a.name));
const eventNames = new Set((idl.events ?? []).map((e) => e.name));
const byName = new Map(idl.types.map((t) => [t.name, t]));
const flatAccounts = (accounts) =>
	accounts.map((a) => {
		if (a.accounts) return { name: camel(a.name), accounts: flatAccounts(a.accounts) };
		return {
			name: camel(a.name),
			isMut: Boolean(a.writable),
			isSigner: Boolean(a.signer),
			...(a.optional ? { isOptional: true } : {}),
		};
	});
const legacy = {
	version: idl.metadata.version,
	name: idl.metadata.name,
	instructions: idl.instructions.map((ix) => ({
		name: camel(ix.name),
		accounts: flatAccounts(ix.accounts),
		args: ix.args.map(field),
	})),
	accounts: idl.accounts.map((a) => typeDef(byName.get(a.name))),
	types: idl.types.filter((t) => !accountNames.has(t.name) && !eventNames.has(t.name)).map(typeDef),
	events: (idl.events ?? []).map((e) => {
		const t = byName.get(e.name);
		return { name: e.name, fields: t.type.fields.map((f) => ({ ...field(f), index: false })) };
	}),
	errors: (idl.errors ?? []).map((e) => ({ code: e.code, name: e.name, msg: e.msg ?? "" })),
	metadata: { address: idl.address },
};
const out = fileURLToPath(new URL("../packages/sdk/src/artifacts/", import.meta.url));
mkdirSync(out, { recursive: true });
const json = JSON.stringify(legacy, null, 2);
writeFileSync(`${out}solve.json`, `${json}\n`);
writeFileSync(
	`${out}solve.ts`,
	`// Generated by scripts/convert-idl.mjs from idl/solve.json. Do not edit.\nexport type Solve = ${json};\n\nexport const IDL: Solve = ${json};\n`,
);
console.log(`instructions ${legacy.instructions.length}, accounts ${legacy.accounts.length}, types ${legacy.types.length}, events ${legacy.events.length}, errors ${legacy.errors.length}`);
